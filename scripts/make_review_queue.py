"""Generates docs/REVIEW_QUEUE.md from data/processed/tests.csv, data/llm/bass2_outcome_proposals.csv and data/review/.

Run after `python -m pipeline`:  python scripts/make_review_queue.py
Human decisions are NOT written here: they go into data/review/outcome_review.csv (see data/llm/README.md).
"""
import collections
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'docs' / 'REVIEW_QUEUE.md'


def read(path):
    with open(path, newline='', encoding='utf-8') as f:
        return list(csv.DictReader(f))


def esc(t):
    return (t or '').replace('|', '\\|').replace('\n', ' ')


def main():
    rows = read(ROOT / 'data/processed/tests.csv')
    props = read(ROOT / 'data/llm/bass2_outcome_proposals.csv')
    review = {r['test_id']: r for r in read(ROOT / 'data/review/outcome_review.csv') if r.get('decision')}
    by_id = {r['test_id']: r for r in rows}
    L = ['# Review queue', '',
         'Generated by `scripts/make_review_queue.py` from the processed table and the sidecar files. Nothing in this queue is used downstream until a person decides. '
         'Record BASS-II decisions in `data/review/outcome_review.csv` (columns `test_id, decision, approved_class, reviewer, reviewed_on, note`; decision = approved, rejected or changed). '
         'Only approved or changed classes reach `outcome_class`; all other BASS-II rows stay `unknown` (decision D12).', '']
    # ---- 1. BASS-II proposals
    cnt = collections.Counter((p['proposed_class'], p['confidence']) for p in props)
    L += ['## 1. BASS-II outcome proposals (LLM, decision D12)', '',
          f'{len(props)} tests. Proposer: {props[0]["model"]}, rubric `{props[0]["rubric_version"]}` (data/llm/README.md), {props[0]["proposed_on"]}. '
          'Original observation text: NTRS 20210011385 Appendix A (PDF p.111-121). O20-O22 are not in Appendix A and stay unknown.', '',
          '| proposed class | high | medium | low | total |', '|---|---|---|---|---|']
    classes = sorted({p['proposed_class'] for p in props})
    for c in classes:
        h, m, lo = (cnt[(c, k)] for k in ('high', 'medium', 'low'))
        L.append(f'| {c} | {h} | {m} | {lo} | {h + m + lo} |')
    L += ['', 'Review the low and medium confidence rows first. Decided rows: ' + str(len(review)) + ' of ' + str(len(props)) + '.', '',
          '| test_id | original observation (Appendix A) | proposed | confidence | rationale | decision |', '|---|---|---|---|---|---|']
    order = {'low': 0, 'medium': 1, 'high': 2}
    for p in sorted(props, key=lambda p: (order[p['confidence']], p['test_id'])):
        rv = review.get(p['test_id'])
        dec = f"{rv['decision']} ({rv['approved_class'] or p['proposed_class']})" if rv else ''
        L.append(f"| {p['test_id'].split(':')[1]} | {esc(p['observation_text'])} | {p['proposed_class']} | {p['confidence']} | {esc(p['rationale'])} | {dec} |")
    # ---- 2. CFI-G comment-based decisions
    cf = [r for r in rows if r['family'] == 'CFI-G' and any(f in r['quality_flags'] for f in ('class_from_comment', 'label_conflict', 'hot_ignition_value_flash'))]
    L += ['', '## 2. CFI-G rows decided by a comment or with a label conflict (decision D10)', '',
          'Rule: SE -> self_extinguished, FT -> externally_terminated (FT confirmed by the UMD thesis, SE consistent with its "radiatively extinguished"; see OUTCOME_MAPPING.md). '
          'Comment-based overrides carry the flag `class_from_comment`; "flash" rows are `unknown`.', '',
          '| test_id | raw label | comment | class | flags |', '|---|---|---|---|---|']
    for r in cf:
        if 'hot_ignition_value_flash' in r['quality_flags'] and 'class_from_comment' not in r['quality_flags'] and 'label_conflict' not in r['quality_flags']:
            continue
        L.append(f"| {r['test_id']} | {esc(r['outcome_raw'])} | {esc(json.loads(r['ext']).get('comments', ''))} | {r['outcome_class']} | {esc(r['quality_flags'])} |")
    n_flash = sum(1 for r in cf if 'hot_ignition_value_flash' in r['quality_flags'])
    L += ['', f'Plus {n_flash} rows with hot ignition = "flash" (undocumented), all `unknown`.']
    # ---- 3. FLEX label vs diameter (D22)
    fx = [r for r in rows if r['family'] == 'FLEX' and 'diameter_label_disagree' in r['quality_flags']]
    L += ['', '## 3. FLEX: "Test end" label versus extinction diameter (decision D22)', '',
          "The outcome class comes from the report's \"Test end\" label (Extinction = self_extinguished, Completion = burned_to_completion, Disruption = other). "
          'The visible flame extinction diameter is only a consistency check: a positive diameter should go with "Extinction", a dash or zero with the other labels. '
          f'**{len(fx)} rows disagree** (listed below). The label wins in the data; the diameter is kept in `ext.extinction_diameter_mm`.', '',
          '| test_id | Test end (label) | extinction diameter (mm) | class |', '|---|---|---|---|']
    for r in fx:
        e = json.loads(r['ext'])
        L.append(f"| {r['test_id']} | {r['outcome_raw']} | {e.get('extinction_diameter_mm', '') or '(blank)'} | {r['outcome_class']} |")
    # ---- 4. Saffire cross-checks
    L += ['', '## 4. Saffire: PSI tables versus the report (NTRS 20170008805, slide 29, Table I), decision D24', '',
          '| item | PSI value | report value | handling |', '|---|---|---|---|',
          '| PSI-99 thickness "037 mm" (2-4, 2-5, 2-6) | 037 mm | 0.37 mm | **corrected** to 0.37 mm, flag `corrected_from_report` |',
          '| PSI-98 length and width | length 40.6, width 94 | width 40.6 cm, length 94 cm | **corrected** (swapped back), flag `corrected_from_report` |',
          '| PSI-99 samples 2-6 and 2-9 material | blank | 2-6: Cotton-Fiberglass; 2-9: PMMA | **filled** from the report, flag `corrected_from_report` |',
          '| PSI-99 sample 2-6 air flow | 20 cm/s | 25 cm/s | **genuine conflict**: PSI kept, report value in `alt_value_report`, flag `source_conflict`; see CONFLICTS.md |',
          '| PSI-99 "?-g Spread Length" | mm/s values | column is "?-g Spread Rate" | **applied** (D14), flag `header_corrected` |',
          '| Saffire-I microgravity burn length and spread rate | not in PSI-98 | sample 1-1: ~84 cm, 1.8 mm/s; 1-2: ~10 cm, 1.3 mm/s | not used; could enrich PSI-98 |', '']
    # ---- 5. BASS-II pressure statements not applied
    L += ['## 5. BASS-II pressure statements not applied (scope unclear)', '',
          'Applied (D12): "1 atm" for B3, B4, B11, B13 (figure caption, PDF p.49) and for the 27 T\'ien SIBAL tests (section 7.1.3, PDF p.102), flag `nominal`. Not applied because the scope is not stated per test:', '',
          '- PDF p.46: "The total pressure is also monitored, which varied from 99.2 to 99.5 kPa in the tests reported" (Bhattacharjee section).',
          '- PDF p.30 and p.33: "20.7 percent O2, 1 atm" and "21/79 ... at 1 atm" for specific figures.', '']
    # ---- 6. other flags worth a look
    o2 = [r['test_id'] for r in rows if 'o2_final_differs_from_initial_by_more_than_3pct' in r['quality_flags']]
    t51 = [r['test_id'] for r in rows if 'table_5_1_o2_differs_from_psi' in r['quality_flags']]
    L += ['## 6. Other items', '',
          f"- BASS-II rows whose final O2 differs from the initial by more than 3 vol% (kept as written): {', '.join(x.split(':')[1] for x in o2) or 'none'}.",
          f"- BASS-II Table 5.1 rows whose initial O2 differs from the PSI value: {', '.join(x.split(':')[1] for x in t51) or 'none'}.",
          '- BASS (PSI-26) is no longer part of the structured table (decision D13); it is for the evidence ledger (M3).',
          '- The 91 CFI-G `externally_terminated` rows are censored; decide how the envelope model uses them (OUTCOME_MAPPING.md).', '']
    OUT.write_text('\n'.join(L) + '\n', encoding='utf-8')
    print(f'wrote {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
