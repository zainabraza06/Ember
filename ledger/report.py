"""docs/LEDGER_REPORT.md, generated from claims.jsonl, rejected.jsonl, the usage log, the run log and pilot.json."""
import collections
import json

from . import config
from .llm import RUN_LOG, read_usage, usage_totals
from .pages import read_sources
from .review import audit_stats

PILOT_JSON = config.LEDGER_DIR / 'pilot.json'


def read_jsonl(path):
    if not path.exists():
        return []
    with open(path, encoding='utf-8') as f:
        return [json.loads(line) for line in f]


def load_pilots():
    return json.loads(PILOT_JSON.read_text(encoding='utf-8')) if PILOT_JSON.exists() else []


def save_pilot(entry):
    pilots = load_pilots()
    pilots = [p for p in pilots if p['prompt_version'] != entry['prompt_version']] + [entry]
    PILOT_JSON.write_text(json.dumps(pilots, indent=1, sort_keys=True) + '\n', encoding='utf-8')


def pilot_passed(prompt_version):
    return any(p['prompt_version'] == prompt_version and p['passed'] for p in load_pilots())


def write_report(stats=None):
    kept, rej = read_jsonl(config.CLAIMS_JSONL), read_jsonl(config.REJECTED_JSONL)
    allc = kept + rej
    srcs = read_sources()
    L = ['# Ledger report (M3)', '', 'Generated by `python -m ledger report` from `data/ledger/` (claims, rejected, usage log, run log, pilot results). Do not edit by hand.', '']
    status = collections.Counter(c['status'] for c in allc)
    L += ['## 1. Documents and claims', '',
          f"{len(srcs)} documents in `data/ledger/sources.csv`; {sum(1 for c in allc)} claims extracted (after parsing); "
          f"**{status['verified_auto']} verified_auto, {status['approved']} approved, {status['pending_verification']} pending_verification (unreviewed; passed the code checks, no independent verifier ran), {status['needs_review']} needs_review, {status['rejected']} rejected.**", '',
          '| document | scope (PDF pages) | claims | verified_auto | needs_review | rejected | verbatim display |', '|---|---|---|---|---|---|---|']
    for s in srcs:
        cs = [c for c in allc if c['doc_id'] == s['doc_id']]
        n = collections.Counter(c['status'] for c in cs)
        L.append(f"| {s['doc_id']} {s['title'][:60]} | {s['scope_pages'] or 'all'} | {len(cs)} | {n['verified_auto'] + n['approved']} | {n['needs_review']} | {n['rejected']} | {s['display_verbatim']} |")
    L += ['', '## 2. Results per check', '',
          'Counts over all extracted claims. A claim can fail more than one check.', '',
          '| check | pass | fail / flagged | note |', '|---|---|---|---|']
    def cnt(fn):
        return sum(1 for c in allc if fn(c))
    sp = collections.Counter(c['verification']['span']['result'] for c in allc)
    L.append(f"| span (exact / fuzzy>=0.95 / not found) | {sp['exact']} exact | {sp['fuzzy']} fuzzy, {sp['fail']} not found (rejected) | {cnt(lambda c: c['verification']['span'].get('page_corrected'))} had a wrong page that was corrected from the text |")
    nm = collections.Counter(c['verification']['numbers']['result'] for c in allc)
    L.append(f"| numbers of the claim appear in the span | {nm['pass']} | {nm['fail']} (needs_review) | |")
    cd = collections.Counter(c['verification']['conditions']['result'] for c in allc)
    L.append(f"| numeric conditions derivable from the span | {cd['pass']} | {cd['fail']} (needs_review) | |")
    gv = collections.Counter(c['verification']['gravity']['result'] for c in allc)
    L.append(f"| gravity class word present | {gv['pass']} in span, {gv['context']} on the page only | {gv['fail']} (needs_review) | |")
    su = collections.Counter(c['verification']['support']['result'] for c in allc)
    L.append(f"| LLM support check | {su['supported']} supported | {su['partial']} partial (needs_review), {su['unsupported']} unsupported (rejected), {su['error']} error, {su['pending']} pending | separate prompt `{config.VERIFY_PROMPT_VERSION}` |")
    low = cnt(lambda c: c['extraction_confidence'] == 'low')
    L.append(f"| extraction confidence | {len(allc) - low} high/medium | {low} low (needs_review) | |")
    L += ['', '## 3. Claims per gravity level (verified_auto + approved; in brackets: all non-rejected)', '',
          '| gravity class | public claims | all non-rejected | documents |', '|---|---|---|---|']
    pub = [c for c in kept if c['status'] in ('verified_auto', 'approved')]
    for g in ['microgravity', 'lunar', 'mars', 'partial_other', 'earth_1g', 'not_stated']:
        a = [c for c in pub if c['conditions']['gravity_class'] == g]
        b = [c for c in kept if c['conditions']['gravity_class'] == g]
        L.append(f"| {g} | {len(a)} | {len(b)} | {len({c['doc_id'] for c in b})} |")
    L += ['', f"**Lunar: {sum(1 for c in pub if c['conditions']['gravity_class'] == 'lunar')} public claims. Mars: {sum(1 for c in pub if c['conditions']['gravity_class'] == 'mars')} public claims.**", '']
    grp = collections.Counter(c.get('independent_sources', 0) for c in pub)
    L += ['## 4. Groups', '',
          f"{len({c['group_id'] for c in pub if c.get('group_id')})} groups over {len(pub)} public claims; groups by independent-source count: "
          + ', '.join(f'{k} source(s): {v} claims' for k, v in sorted(grp.items())) + '.', '']
    L += ['## 5. Pilot (FLEX NTRS 20150023456 and BASS-II NTRS 20210011385)', '']
    pilots = load_pilots()
    if pilots:
        L += ['| extract prompt | verify prompt | claims | failing a check | fail rate | passed (<= 30%) | model version(s) |', '|---|---|---|---|---|---|---|']
        for p in sorted(pilots, key=lambda p: p['prompt_version']):
            L.append(f"| {p['prompt_version']} | {p['verify_prompt']} | {p['claims']} | {p['failed']} | {p['fail_rate']:.1%} | {'yes' if p['passed'] else 'no'} | {', '.join(p['model_versions'])} |")
        L += ['', 'Failure here means a claim rejected or flagged by the span, number, condition, gravity or LLM support check (low extraction confidence alone is not a failure). Prompt changes between versions are described in `prompts/CHANGELOG.md`.', '']
    else:
        L += ['Not run yet.', '']
    tokens, requests = usage_totals()
    usage = read_usage()
    by_prov = collections.defaultdict(lambda: {'requests': 0, 'tokens': 0, 'models': set(), 'kinds': collections.Counter()})
    for u in usage:
        d = by_prov[u.get('provider', '?')]
        d['requests'] += 1
        d['tokens'] += u.get('total_tokens', 0)
        d['models'].add(u.get('model_version', ''))
        d['kinds'][u['kind']] += 1
    L += ['## 6. Models and usage (decisions D31, D32)', '',
          'Extraction and verification use **two different model families** (Google Gemini for extraction, Meta Llama 3.3 70B served by Groq for the support check and the BASS-II second rater), '
          'so the model that wrote a claim is not the model that checks it. Both are LLM judgements; the span and number checks are plain code.', '',
          '| provider | role | requested model | exact version(s) returned | requests | tokens |', '|---|---|---|---|---|---|']
    roles = {'gemini': 'extraction', 'groq': 'support check, BASS-II second rater'}
    for prov in ('gemini', 'groq'):
        d = by_prov.get(prov)
        L.append(f"| {prov} | {roles[prov]} | `{config.PROVIDERS[prov]['model'] or 'not chosen'}` | " + (', '.join('`' + m + '`' for m in sorted(d['models'])) if d else 'none yet')
                 + f" | {d['requests'] if d else 0} | {d['tokens'] if d else 0:,} |")
    L += ['', f"Total **{tokens:,} tokens in {requests} requests** (cap LEDGER_MAX_TOKENS {config.MAX_TOKENS:,}). Per-provider limits used by the client (requests/minute, requests/day): "
          + '; '.join(f"{k} {int(v['rpm'])}/min, {int(v['rpd'])}/day" for k, v in config.PROVIDERS.items())
          + ' (placeholders unless overwritten from the account limits pages; see SI_USAGE.md). The exact versions are also pinned in every cache entry (`data/ledger/cache/`).', '']
    ev = read_jsonl(RUN_LOG)
    retries = [e for e in ev if e['event'] == 'retry']
    stops = [e for e in ev if e['event'] in ('stopped', 'rate_limit_exhausted', 'daily_limit')]
    L += [f"Rate-limit / transient-error interruptions: {len(retries)} retried calls (codes: {dict(collections.Counter(str(e.get('http', e.get('error'))) for e in retries))}); {len(stops)} stops"
          + ('. ' + '; '.join(f"{e['t']} {e.get('reason', e.get('what', ''))}" for e in stops[-10:]) if stops else '') + '.', '']
    done, yes = audit_stats()
    L += ['## 7. Human audit', '',
          f"CLAIM_AUDIT.md: {done} of 30 sampled claims judged so far; " + (f"{yes} correct ({yes / done:.0%}); target >= 90%." if done else 'none judged yet (target >= 90% correct).'),
          f"Review queue: {status['needs_review']} claims in `data/review/claim_review.csv` await a decision.", '']
    if stats and (stats.get('stopped') or stats.get('failed_chunks') or stats.get('pending_chunks')):
        L += ['## 8. Last run did not complete', '', f"Stopped: {stats.get('stopped')}. Pending chunks: {len(stats.get('pending_chunks', []))}; failed chunks: {stats.get('failed_chunks')}. "
              'Rerun `python -m ledger`; finished calls are cached and are not repeated.', '']
    config.REPORT_MD.write_text('\n'.join(L) + '\n', encoding='utf-8')
