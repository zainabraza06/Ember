"""D30: an independent second rater (Groq, Llama 3.3 70B) classifies the BASS-II observations with the same rubric as the Claude Code
proposals (data/llm/bass2_outcome_proposals.csv). It sees only the observation text. Results go to data/llm/bass2_outcome_second_rater.csv
and docs/BASS2_SECOND_RATER.md (agreement rate, Cohen's kappa, confusion matrix). Nothing here changes outcome_class: only a person can
approve a class in data/review/outcome_review.csv."""
import collections
import csv
import json

from . import config
from .llm import STOPS, CacheMiss

CLASSES = ['no_ignition', 'self_extinguished', 'burned_to_completion', 'externally_terminated', 'other', 'unknown']
PROMPT_VERSION = 'bass2_rater_v1'
OBS_CSV = config.ROOT / 'data' / 'transcribed' / 'sidecars' / 'bass2_observations.csv'
PROPOSALS_CSV = config.ROOT / 'data' / 'llm' / 'bass2_outcome_proposals.csv'
OUT_CSV = config.ROOT / 'data' / 'llm' / 'bass2_outcome_second_rater.csv'
OUT_MD = config.ROOT / 'docs' / 'BASS2_SECOND_RATER.md'
FIELDS = ['test_id', 'observation_text', 'rater_class', 'rater_confidence', 'rater_rationale', 'model_version', 'prompt_version']


def cohens_kappa(a, b, labels=CLASSES):
    n = len(a)
    if n == 0:
        return float('nan')
    po = sum(1 for x, y in zip(a, b) if x == y) / n
    ca, cb = collections.Counter(a), collections.Counter(b)
    pe = sum(ca[k] * cb[k] for k in labels) / (n * n)
    return 1.0 if pe == 1 else (po - pe) / (1 - pe)


def rate_all(client):
    text = (config.PROMPTS_DIR / f'{PROMPT_VERSION}.md').read_text(encoding='utf-8')
    with open(OBS_CSV, encoding='utf-8') as f:
        obs = list(csv.DictReader(f))
    out, pending, stopped = [], 0, None
    for o in obs:
        if not o['observation_text'].strip():
            continue
        if stopped:
            pending += 1
            continue
        try:
            e = client.complete('rate', 'bass2-observations', o['test_id'], PROMPT_VERSION, text, 'Observation text:\n' + o['observation_text'],
                                max_tokens=300, tag='bass2')
        except CacheMiss:
            pending += 1
            continue
        except STOPS as ex:
            stopped = f'{type(ex).__name__}: {ex}'
            pending += 1
            continue
        row = {'test_id': o['test_id'], 'observation_text': o['observation_text'], 'model_version': e['model_version'], 'prompt_version': PROMPT_VERSION}
        try:
            j = json.loads(e['content'])
            row.update(rater_class=j['class'] if j['class'] in CLASSES else 'invalid', rater_confidence=j.get('confidence', ''),
                       rater_rationale=str(j.get('rationale', ''))[:300])
        except (ValueError, KeyError, TypeError):
            row.update(rater_class='invalid', rater_confidence='', rater_rationale='unparseable')
        out.append(row)
    return out, pending, stopped


def write_outputs(rows, pending, stopped):
    with open(OUT_CSV, 'w', newline='', encoding='utf-8') as f:
        w = csv.DictWriter(f, fieldnames=FIELDS, lineterminator='\n')
        w.writeheader()
        w.writerows(rows)
    with open(PROPOSALS_CSV, encoding='utf-8') as f:
        prop = {r['test_id']: r for r in csv.DictReader(f)}
    pairs = [(prop[r['test_id']]['proposed_class'], r['rater_class'], r) for r in rows if r['test_id'] in prop]
    a, b = [p[0] for p in pairs], [p[1] for p in pairs]
    agree = sum(1 for x, y in zip(a, b) if x == y)
    kappa = cohens_kappa(a, b)
    models = ', '.join(sorted({r['model_version'] for r in rows})) or 'n/a'
    L = ['# BASS-II second rater (decision D30)', '',
         'Generated by `python -m ledger rate`. Rater 1 = the Claude Code proposals (`data/llm/bass2_outcome_proposals.csv`, made by reading the text, see SI_USAGE.md). '
         f'Rater 2 = Groq `{models}` with `prompts/{PROMPT_VERSION}.md` (same rubric, sees only the observation text). '
         'Neither rating is used downstream until a person approves a class in `data/review/outcome_review.csv`.', '']
    if not pairs:
        L += ['Not run yet.']
    else:
        L += [f'**Compared tests: {len(pairs)}. Agreement: {agree}/{len(pairs)} = {agree / len(pairs):.1%}. Cohen kappa: {kappa:.3f}.**'
              + (f' Incomplete: {pending} tests pending ({stopped}).' if pending else ''), '',
              'Rows = Claude Code proposal, columns = second rater.', '', '| | ' + ' | '.join(CLASSES) + ' | invalid |', '|---|' + '---|' * (len(CLASSES) + 1)]
        cm = collections.Counter(zip(a, b))
        for c1 in CLASSES:
            L.append(f'| {c1} | ' + ' | '.join(str(cm[(c1, c2)]) for c2 in CLASSES + ['invalid']) + ' |')
        L += ['', '## Disagreements (for the human reviewer)', '', '| test_id | observation | Claude Code | second rater | second rater rationale |', '|---|---|---|---|---|']
        for x, y, r in pairs:
            if x != y:
                L.append(f"| {r['test_id']} | {r['observation_text'].replace('|', '/')[:200]} | {x} | {y} | {r['rater_rationale'].replace('|', '/')} |")
        L += ['', 'Agreement between two raters does not make a class correct; it only shows where the text is clear. '
              'Disagreements and all low-confidence proposals go to a person (REVIEW_QUEUE.md section 1).']
    OUT_MD.write_text('\n'.join(L) + '\n', encoding='utf-8')
    return len(pairs), agree, kappa
